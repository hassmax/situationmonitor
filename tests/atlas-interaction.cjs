const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const code = fs.readFileSync('site/app.js', 'utf8');
const section = (a, b) => code.slice(code.indexOf(a), code.indexOf(b, code.indexOf(a)));
const eventTarget = () => ({ handlers: {}, addEventListener(k, fn) { this.handlers[k] = fn; }, fire(k) { this.handlers[k]?.(); } });
function rotation(reduceMotion = false) {
  let now = 0, id = 0;
  const timers = new Map(), document = { ...eventTarget(), hidden: false };
  const orbit = { ...eventTarget(), autoRotate: false };
  const button = { ...eventTarget(), dataset: {}, setAttribute(k, v) { this[k] = v; } };
  const ctx = { reduceMotion, document, updateRenderRatio() {}, setTimeout(fn, ms) { timers.set(++id, { at: now + ms, fn }); return id; }, clearTimeout(id) { timers.delete(id); } };
  vm.createContext(ctx);
  vm.runInContext(section('  function setupIdleRotation(', '  // ------------------------------------------------------------------ land, borders'), ctx);
  ctx.setupIdleRotation(orbit, button);
  const advance = ms => { now += ms; for (const [id, task] of timers) if (task.at <= now) { timers.delete(id); task.fn(); } };
  return { orbit, button, document, advance };
}
let r = rotation();
r.advance(29999); assert.equal(r.orbit.autoRotate, false);
r.advance(1); assert.equal(r.orbit.autoRotate, true);
assert.ok(r.orbit.autoRotateSpeed > 0 && r.orbit.autoRotateSpeed < 0.3);
r.orbit.fire('start'); assert.equal(r.orbit.autoRotate, false);
r.document.fire('pointerdown'); r.advance(60000); assert.equal(r.orbit.autoRotate, false, 'holding a drag cannot resume rotation');
r.orbit.fire('end'); r.advance(29999); assert.equal(r.orbit.autoRotate, false);
r.advance(1); assert.equal(r.orbit.autoRotate, true);
r.button.fire('click'); r.advance(60000); assert.equal(r.orbit.autoRotate, false, 'explicit pause persists');
r.button.fire('click'); r.advance(30000); assert.equal(r.orbit.autoRotate, true);
r.document.hidden = true; r.document.fire('visibilitychange'); assert.equal(r.orbit.autoRotate, false);
r.advance(60000); assert.equal(r.orbit.autoRotate, false);
r.document.hidden = false; r.document.fire('visibilitychange'); r.advance(29999); assert.equal(r.orbit.autoRotate, false);
r.advance(1); assert.equal(r.orbit.autoRotate, true);
r.document.fire('keydown'); r.advance(29999); assert.equal(r.orbit.autoRotate, false);
r = rotation(true); r.advance(60000); assert.equal(r.orbit.autoRotate, false, 'reduced motion starts paused');
r.button.fire('click'); r.advance(30000); assert.equal(r.orbit.autoRotate, true, 'explicit opt-in is allowed');
const S = { region: 'world', theaters: [{id:'ukraine',highlight:['804']},{id:'mideast',highlight:['887']},{id:'horn',highlight:['729']},{id:'hidden',listed:false,highlight:['999']}] };
const ctx = { S, ISO_NUM: new Map([['UA','804']]) };
vm.createContext(ctx);
vm.runInContext(section('  const CONTROL_THEATER', '  // Infiltration'), ctx);
assert.equal(ctx.controlInRegion({conflict:'ukraine'}), true);
assert.equal(ctx.controlInRegion({conflict:'unknown'}), false);
assert.equal(ctx.controlInRegion({country:'999'}), false);
S.region = 'mideast';
assert.equal(ctx.controlInRegion({conflict:'ukraine'}), false);
assert.equal(ctx.controlInRegion({conflict:'yemen'}), true);
assert.equal(ctx.controlInRegion({country:'UA'}), false);
S.region = 'ukraine'; assert.equal(ctx.controlInRegion({country:'UA'}), true);
S.region = null; assert.equal(ctx.controlInRegion({conflict:'ukraine'}), false);
assert.ok(!fs.readFileSync('site/index.html','utf8').includes('A world in motion'));
console.log('PASS: 30-second idle rotation, drag hold/reset, pause/resume, visibility, reduced motion, and territorial region filtering.');
